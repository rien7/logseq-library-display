import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dirname, "..");
const outputPath = path.join(root, "src", "generated", "icon-data.ts");

const emojiDataPath = require.resolve("@emoji-mart/data/sets/15/native.json");
const tablerCssPath = require.resolve("@tabler/icons-webfont/dist/tabler-icons.min.css");

const emojiData = JSON.parse(fs.readFileSync(emojiDataPath, "utf8"));
const tablerCss = fs.readFileSync(tablerCssPath, "utf8");

const emojiById = {};
for (const [id, emoji] of Object.entries(emojiData.emojis ?? {})) {
  const native = emoji?.skins?.[0]?.native;
  if (typeof native === "string" && native) {
    emojiById[id] = native;
  }
}

const tablerCodepointById = {};
const tablerRule = /\.ti-([a-z0-9-]+):before\{content:"\\([0-9a-f]+)"\}/g;
let match;
while ((match = tablerRule.exec(tablerCss))) {
  tablerCodepointById[match[1]] = String.fromCodePoint(parseInt(match[2], 16));
}

function emitRecord(name, value) {
  const entries = Object.entries(value).sort(([left], [right]) => left.localeCompare(right));
  const body = entries
    .map(([key, item]) => `  ${JSON.stringify(key)}: ${JSON.stringify(item)},`)
    .join("\n");

  return `export const ${name}: Record<string, string> = {\n${body}\n};`;
}

const source = [
  "// Generated by scripts/generate-icon-data.mjs. Do not edit manually.",
  emitRecord("EMOJI_BY_ID", emojiById),
  emitRecord("TABLER_CODEPOINT_BY_ID", tablerCodepointById),
  "",
].join("\n\n");

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source);

console.log(
  `Generated ${path.relative(root, outputPath)} (${Object.keys(emojiById).length} emoji, ${Object.keys(tablerCodepointById).length} tabler icons)`,
);
